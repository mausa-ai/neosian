"""The publishing posture (NX, DESIGN §29; the one release of §39.5),
pinned keylessly: least privilege at the top of every hand-written
workflow, every action by commit SHA with its version beside it, the base
images by their index digests, the one uv pin across Python installers, Dependabot
over all four ecosystems, and the sdist declaring what never ships. The
generated release.yml is cargo-dist's (ledger #350): its permissions are
what it generates, its actions are the commits dist-workspace.toml names,
and `dist generate --check` keeps it current. A drift here would
otherwise surface only on the release that carries it."""

import re
import tomllib
from pathlib import Path
from typing import Any

import pytest
import yaml

import neosian

_ROOT = Path(__file__).resolve().parents[2]
_GENERATED = _ROOT / ".github" / "workflows" / "release.yml"
_WORKFLOWS = sorted(
    path
    for path in (_ROOT / ".github" / "workflows").glob("*.yml")
    if path != _GENERATED
)
_DOCKERFILE = _ROOT / "Dockerfile"
_PINNED_USE = re.compile(
    r"^\s*(?:-\s*)?uses:\s*\S+@[0-9a-f]{40}\s+# v\d+\.\d+\.\d+\s*$"
)
_GENERATED_USE = re.compile(r"^\s*(?:-\s*)?uses:\s*(\S+)@([0-9a-f]{40})\s*$")
_ANY_USE = re.compile(r"^\s*(?:-\s*)?uses:")
_BASE = re.compile(r"^FROM (\S+)(?: AS \w+)?$", re.M)
_BACKENDS_LABEL = "ai.mausa.neosian.backends"


def _workflow(path: Path) -> dict[Any, Any]:
    # YAML 1.1 reads the `on` key as the boolean True — hence the key type.
    loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert isinstance(loaded, dict)
    return loaded


@pytest.mark.unit
@pytest.mark.parametrize("path", _WORKFLOWS, ids=lambda p: p.name)
def test_every_workflow_starts_least_privileged(path: Path) -> None:
    assert _workflow(path)["permissions"] == {"contents": "read"}


@pytest.mark.unit
@pytest.mark.parametrize("path", _WORKFLOWS, ids=lambda p: p.name)
def test_every_action_is_pinned_by_sha(path: Path) -> None:
    uses = [
        ln for ln in path.read_text(encoding="utf-8").splitlines() if _ANY_USE.match(ln)
    ]
    assert uses, f"{path.name} uses no action"
    unpinned = [ln.strip() for ln in uses if not _PINNED_USE.match(ln)]
    assert not unpinned, unpinned


@pytest.mark.unit
def test_the_generated_release_is_pinned_by_its_config() -> None:
    # cargo-dist writes release.yml from dist-workspace.toml (#350): the
    # header says so, every action is one of the commits the config names,
    # and the Python half is called as the one custom publish job.
    text = _GENERATED.read_text(encoding="utf-8")
    assert text.startswith("# This file was autogenerated by dist")
    with (_ROOT / "dist-workspace.toml").open("rb") as f:
        dist = tomllib.load(f)["dist"]
    commits = dist["github-action-commits"]
    uses = [ln for ln in text.splitlines() if _ANY_USE.match(ln)]
    for line in uses:
        if "./.github/workflows/" in line:
            assert line.strip() in {
                "uses: ./.github/workflows/publish-python.yml",
                "uses: ./.github/workflows/publish-channels.yml",
            }
            continue
        matched = _GENERATED_USE.match(line)
        assert matched, line
        assert commits[matched.group(1)] == matched.group(2), line
    assert dist["publish-jobs"] == ["./publish-python", "./publish-channels"]
    assert dist["publish-prereleases"] is False
    release = _workflow(_GENERATED)
    assert release["permissions"] == {"contents": "write"}
    assert release[True]["push"]["tags"]
    assert {"custom-publish-python", "custom-publish-channels"} <= set(
        release["jobs"]["announce"]["needs"]
    )


@pytest.mark.unit
def test_the_image_pins_both_bases_and_the_repository_toolchain() -> None:
    bases = _BASE.findall(_DOCKERFILE.read_text(encoding="utf-8"))
    assert len(bases) == 2, "a builder and a distroless runtime"
    assert all(re.fullmatch(r"[^@]+@sha256:[0-9a-f]{64}", base) for base in bases)
    with (_ROOT / "rust-toolchain.toml").open("rb") as f:
        channel = tomllib.load(f)["toolchain"]["channel"]
    assert bases[0].split("@")[0] == f"rust:{channel}-alpine"
    assert bases[1].startswith("gcr.io/distroless/static-debian13:nonroot@")


@pytest.mark.unit
def test_the_image_names_its_backends_and_the_container_test_reads_them() -> None:
    # R2 slice B (#372): the container test runs one leg per backend the
    # image's label names, so the Rust image at D narrows it to `file`
    # and the Postgres leg skips by name until R4.
    label = re.search(
        rf'^LABEL {re.escape(_BACKENDS_LABEL)}="([^"]+)"$',
        _DOCKERFILE.read_text(encoding="utf-8"),
        re.M,
    )
    assert label is not None, "the image names its backends"
    backends = label.group(1).split(",")
    assert "file" in backends and set(backends) <= {"file", "postgres"}
    script = (_ROOT / "scripts" / "container_test.sh").read_text(encoding="utf-8")
    assert f'"{_BACKENDS_LABEL}"' in script, "the script reads the label"


@pytest.mark.unit
def test_the_one_uv_pin_names_the_same_release_everywhere() -> None:
    # The Rust image needs no uv. The installer and every Python
    # workflow still share one pin (ledger #185, R2 slice D).
    script = (_ROOT / "scripts" / "install.sh").read_text(encoding="utf-8")
    installer = re.search(r'^UV_VERSION="(\d+\.\d+\.\d+)"', script, re.M)
    assert installer
    for path in _WORKFLOWS:
        workflow = _workflow(path)
        if "astral-sh/setup-uv@" in path.read_text(encoding="utf-8"):
            assert workflow["env"]["UV_VERSION"] == installer.group(1), path.name


