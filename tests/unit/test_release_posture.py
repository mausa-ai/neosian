_RELEASE = _ROOT / ".github" / "workflows" / "publish-python.yml"


@pytest.mark.unit
def test_the_release_publishes_by_trust_alone() -> None:
    # DESIGN §29: a `v*` tag publishes (through cargo-dist's release.yml,
    # which calls this workflow once the binaries are hosted, #350); a
    # dispatch rehearses; the only credential is the job's OIDC token,
    # exchanged by uv on the `pypi` environment — no long-lived secret is
    # referenced anywhere.
    text = _RELEASE.read_text(encoding="utf-8")
    release = _workflow(_RELEASE)
    build = release["jobs"]["build"]
    commands = [step.get("run", "") for step in build["steps"]]
    assert commands.index("uv audit --locked") < next(
        i for i, command in enumerate(commands) if command.startswith("uv build ")
    )
    assert release["jobs"]["pypi"]["needs"] == "build"
    assert release["jobs"]["image"]["needs"] == "build"
    triggers = release[True]
    assert triggers["workflow_call"]["inputs"]["plan"]["required"] is True
    assert "workflow_dispatch" in triggers
    assert "secrets." not in text
    pypi = release["jobs"]["pypi"]
    assert pypi["environment"]["name"] == "pypi"
    assert pypi["permissions"]["id-token"] == "write"
    publish = [
        s for s in pypi["steps"] if "--trusted-publishing always" in s.get("run", "")
    ]
    assert len(publish) == 1
    assert publish[0]["if"] == "github.event_name == 'push'"
    others = {name: job for name, job in release["jobs"].items() if name != "pypi"}
    assert not any("id-token" in job.get("permissions", {}) for job in others.values())


