"""Turns stored as records on a FileStore (DESIGN §40.54, T1b1a).

The records home is written here by hand from the design: the enable
marker, a format-2 header row in the turn log and the turn's records file,
each record line carrying the SHA-256 of its canonical encoding. Nothing is
generated by the binary under test.
"""

import hashlib
import json
import shutil
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from tests.contract.support import Binary, serve

SESSION = "c-rec"
WHOLE: dict[str, Any] = {
    "neosian_format": 1,
    "turn": 1,
    "created_at": "2026-11-21T14:00:00Z",
    "messages": [
        {
            "role": "user",
            "content": "first",
            "reasoning": None,
            "tool_calls": [],
            "tool_call_id": None,
        }
    ],
    "actor": "cli:t",
}
ACTOR = "client:default/claude-code:t"
STAMP = "2026-11-21T14:03:07.512000Z"
MESSAGES: list[dict[str, Any]] = [
    {
        "role": "user",
        "content": "héllo",
        "reasoning": None,
        "tool_calls": [],
        "tool_call_id": None,
    },
    {
        "role": "assistant",
        "content": None,
        "reasoning": None,
        "tool_calls": [
            {"id": "toolu_1", "name": "Bash", "arguments": {"command": "ls"}}
        ],
        "tool_call_id": None,
    },
    {
        "role": "tool",
        "content": "a.txt\nb.txt",
        "reasoning": None,
        "tool_calls": [],
        "tool_call_id": "toolu_1",
    },
    {
        "role": "assistant",
        "content": "Two files.",
        "reasoning": None,
        "tool_calls": [],
        "tool_call_id": None,
    },
]


def record(
    seq: int,
    message: int,
    role: str,
    kind: str,
    text: str,
    *,
    content: str | None = "text",
    call: int | None = None,
    call_id: str | None = None,
    name: str | None = None,
    chunk: int = 0,
    size: int | None = None,
) -> dict[str, Any]:
    """One record in write shape, every key in the design's order."""
    return {
        "seq": seq,
        "message": message,
        "role": role,
        "kind": kind,
        "content": content,
        "block": None,
        "call": call,
        "call_id": call_id,
        "name": name,
        "chunk": chunk,
        "size": len(text.encode()) if size is None else size,
        "text": text,
    }


RECORDS = [
    record(0, 0, "user", "prompt", "héllo"),
    record(
        1,
        1,
        "assistant",
        "tool_call",
        '{"command":"ls"}',
        content="none",
        call=0,
        call_id="toolu_1",
        name="Bash",
    ),
    record(2, 2, "tool", "tool_result", "a.txt\nb.txt", call_id="toolu_1"),
    record(3, 3, "assistant", "reply", "Two files."),
]


def canonical(value: dict[str, Any]) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def record_line(value: dict[str, Any]) -> str:
    digest = hashlib.sha256(canonical(value).encode()).hexdigest()
    return canonical({"neosian_format": 1, **value, "sha256": digest}) + "\n"


def header(turn: int, records: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "neosian_format": 2,
        "turn": turn,
        "created_at": STAMP,
        "actor": ACTOR,
        "records": len(records),
        "bytes": sum(len(item["text"].encode()) for item in records),
        "draft": "d7c1e0b2a9f44e57",
    }


def plant(home: Path, records: list[dict[str, Any]], *, marker: bool = True) -> None:
    conversation = home / "conversations" / SESSION
    (conversation / "records").mkdir(parents=True)
    rows = [WHOLE, header(2, records)]
    log = "".join(json.dumps(row, separators=(",", ":")) + "\n" for row in rows)
    (conversation / "turns.jsonl").write_text(log, encoding="utf-8")
    text = "".join(record_line(item) for item in records)
    (conversation / "records" / "2.jsonl").write_text(text, encoding="utf-8")
    if marker:
        (home / ".records").mkdir()
        (home / ".records" / "format").write_text('{"neosian_records":1}\n')


def test_records_enable_writes_its_marker_once(binary: Binary) -> None:
    root = binary.directory / "store"
    root.mkdir()
    first = binary.run("records", "enable", "--root", str(root))
    assert first.returncode == 0, first.stderr
    assert first.stdout == f"records enabled at {root.resolve()}\n"
    marker = root / ".records" / "format"
    assert marker.read_text() == '{"neosian_records":1}\n'
    again = binary.json("records", "enable", "--root", str(root))
    assert again == {
        "root": str(root.resolve()),
        "records": {"version": 1},
        "changed": False,
    }
    home = binary.json("records", "enable")
    assert home["changed"] is True
    assert (binary.home / ".records" / "format").is_file()


def test_records_enable_never_creates_a_store_at_a_missing_root(
    binary: Binary,
) -> None:
    missing = binary.directory / "typo"
    refused = binary.run("records", "enable", "--root", str(missing))
    assert refused.returncode == 1, refused.stderr
    assert "agent_configuration_error" in refused.stderr
    assert f"no store at {missing}" in refused.stderr
    assert not missing.exists()


def test_a_server_refuses_a_bad_record_setting_at_startup(binary: Binary) -> None:
    """DESIGN §40.54 item 23: refused at startup where records are enabled;
    a store without them never reads the record settings."""
    bad = {"NEOSIAN_DRAFT_SECONDS": "59"}
    with serve(binary, extra_env=bad) as server:
        assert (
            server.request("/health", method="GET", authenticated=False).status == 200
        )
    enabled = binary.run("records", "enable")
    assert enabled.returncode == 0, enabled.stderr
    env = {
        **binary.environment(),
        "NEOSIAN_SERVE_TOKEN": "client:contract=contract-admin",
        **bad,
    }
    started = subprocess.run(
        [str(binary.executable), "serve", "--port", "1", "--root", str(binary.home)],
        capture_output=True,
        text=True,
        env=env,
        cwd=binary.directory,
        timeout=30,
        check=False,
    )
    assert started.returncode == 1, started.stderr
    assert "NEOSIAN_DRAFT_SECONDS must be an integer in 60..2592000" in started.stderr


def test_records_enable_refuses_other_stores(binary: Binary) -> None:
    for extra, flags in [
        ({"NEOSIAN_POSTGRES_DSN": "postgresql://nobody@127.0.0.1:9/none"}, []),
        ({"NEOSIAN_CLIENT_TOKEN": "t"}, ["--url", "http://127.0.0.1:9"]),
    ]:
        result = subprocess.run(
            [str(binary.executable), "records", "enable", *flags],
            capture_output=True,
            text=True,
            env={**binary.environment(), **extra},
            cwd=binary.directory,
            timeout=30,
            check=False,
        )
        assert result.returncode == 1, result.stderr
        assert "agent_configuration_error" in result.stderr
        assert "records" in result.stderr
    clash = binary.run("records", "enable", "--root", "x", "--url", "http://h")
    assert clash.returncode == 2
    assert not (binary.home / ".records").exists()


def test_a_planted_records_turn_reads_back_whole(binary: Binary) -> None:
    plant(binary.home, RECORDS)
    with serve(binary) as server:
        turns = server.post("conversation/read_turns", conversation_id=SESSION)
        assert turns["turns"][1] == {
            "conversation_id": SESSION,
            "turn": 2,
            "messages": MESSAGES,
            "created_at": STAMP,
            "actor": ACTOR,
            "redacted": False,
        }
        number = server.post("conversation/last_turn_number", conversation_id=SESSION)
        assert number["turn"] == 2
        appended = server.post(
            "conversation/append_turn",
            conversation_id=SESSION,
            messages=[{"role": "user", "content": "next"}],
        )
        assert appended["turn"]["turn"] == 3
        after = server.post("conversation/read_turns", conversation_id=SESSION, after=2)
        assert [turn["turn"] for turn in after["turns"]] == [3]


def test_a_long_records_turn_is_refused_by_name_on_a_legacy_read(
    binary: Binary,
) -> None:
    text = "x" * 70_000
    records = [
        record(0, 0, "user", "prompt", text[:65_534], size=70_000),
        record(
            1, 0, "user", "prompt", text[65_534:], content=None, chunk=1, size=70_000
        ),
    ]
    plant(binary.home, records)
    with serve(binary, extra_env={"NEOSIAN_MAX_TURN_BYTES": "65536"}) as server:
        reply = server.request(
            "/v1/conversation/read_turns", {"conversation_id": SESSION}
        )
        assert reply.status == 400
        assert reply.body["error"]["code"] == "value_error"
        assert reply.body["error"]["message"] == (
            "resource limit NEOSIAN_MAX_TURN_BYTES exceeded: turn 2 of c-rec holds"
            " 70000 > 65536 bytes; a newer neosian reads this turn in parts"
        )
    with serve(binary) as server:
        turns = server.post("conversation/read_turns", conversation_id=SESSION)
        assert turns["turns"][1]["messages"][0]["content"] == text
    started = subprocess.run(
        [str(binary.executable), "serve", "--port", "1", "--root", str(binary.home)],
        capture_output=True,
        text=True,
        env={
            **binary.environment(),
            "NEOSIAN_SERVE_TOKEN": "client:contract=contract-admin",
            "NEOSIAN_MAX_TURN_BYTES": "65535",
        },
        cwd=binary.directory,
        timeout=30,
        check=False,
    )
    assert started.returncode == 1, started.stderr
    assert started.stderr == (
        "error: NEOSIAN_MAX_TURN_BYTES must be an integer in 65536..1073741824\n"
    )


def test_without_the_marker_a_header_row_is_newer_than_supported(
    binary: Binary,
) -> None:
    plant(binary.home, RECORDS, marker=False)
    with serve(binary) as server:
        for route in ["read_turns", "last_turn_number"]:
            reply = server.request(
                "/v1/conversation/" + route, {"conversation_id": SESSION}
            )
            assert reply.status == 400
            error = reply.body["error"]
            assert error["code"] == "agent_conversation_format_unsupported"
            assert "turn-log line 2 format 2 is newer than supported" in (
                error["message"]
            )


def test_prune_plans_from_headers_so_a_long_records_turn_never_stops_it(
    binary: Binary,
) -> None:
    """A turn longer than `NEOSIAN_MAX_TURN_BYTES` is never assembled by
    `prune` (the T1 review, finding 7): an old conversation holding one is
    planned and erased, a recent one is passed over, and neither stops the
    plan, `--dry-run` included. Erased, the old one is not planned again."""
    text = "x" * 70_000
    records = [
        record(0, 0, "user", "prompt", text[:65_534], size=70_000),
        record(
            1, 0, "user", "prompt", text[65_534:], content=None, chunk=1, size=70_000
        ),
    ]
    plant(binary.home, records)
    recent = binary.home / "conversations" / "c-new"
    shutil.copytree(binary.home / "conversations" / SESSION, recent)
    now = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%S.%fZ")
    log = (recent / "turns.jsonl").read_text(encoding="utf-8")
    log = log.replace(STAMP, now).replace(str(WHOLE["created_at"]), now)
    (recent / "turns.jsonl").write_text(log, encoding="utf-8")

    def prune(*more: str) -> Any:
        pruned = subprocess.run(
            [str(binary.executable), "prune", "--older-than", "1h", "--json", *more],
            capture_output=True,
            text=True,
            env={**binary.environment(), "NEOSIAN_MAX_TURN_BYTES": "65536"},
            cwd=binary.directory,
            timeout=30,
            check=False,
        )
        assert pruned.returncode == 0, pruned.stderr
        return json.loads(pruned.stdout)

    planned = prune("--dry-run")
    assert [row["conversation_id"] for row in planned["conversations"]] == [SESSION]
    assert (planned["turns"], planned["conversations"][0]["turns"]) == (2, 2)
    assert prune()["turns"] == 2
    assert prune("--dry-run")["conversations"] == []
