"""`neosian records migrate` on a FileStore (DESIGN §40.54 item 21, T1b2c3).

The legacy log, the headers and records a migration must write, and a
migration stopped after its durable rename are written here by hand from
the design. Nothing is generated by the binary under test.
"""

import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any

from tests.contract.file.test_records import (
    ACTOR,
    MESSAGES,
    RECORDS,
    SESSION,
    STAMP,
    WHOLE,
    canonical,
    record,
    record_line,
)
from tests.contract.support import Binary, serve

FIRST = [record(0, 0, "user", "prompt", "first")]
TURN_2 = {
    "neosian_format": 1,
    "turn": 2,
    "created_at": STAMP,
    "messages": MESSAGES,
    "actor": ACTOR,
}
SKELETON = {
    "neosian_format": 1,
    "turn": 3,
    "created_at": "2026-11-21T14:05:00Z",
    "messages": [],
    "actor": "cli:t",
    "redacted": True,
}


def ascii_line(row: dict[str, Any]) -> str:
    """A row as every release writes it: compact, ASCII-escaped."""
    return json.dumps(row, separators=(",", ":")) + "\n"


def whole(turn: int, text: str, **extra: Any) -> dict[str, Any]:
    message = {**WHOLE["messages"][0], "content": text}
    return {**WHOLE, "turn": turn, "messages": [message], **extra}


def owner(conversation: str) -> str:
    return "m" + hashlib.sha256(conversation.encode()).hexdigest()[:32]


def header(row: dict[str, Any], records: list[dict[str, Any]], session: str) -> str:
    return ascii_line(
        {
            "neosian_format": 2,
            "turn": row["turn"],
            "created_at": row["created_at"],
            "actor": row["actor"],
            "records": len(records),
            "bytes": sum(len(item["text"].encode()) for item in records),
            "draft": owner(session),
        }
    )


def answer(session: str, migrated: int, records: int, **found: int) -> str:
    kept = {"spelling": 0, "content": 0, "size": 0, "number": 0}
    skeletons = found.pop("skeletons", 0)
    kept.update(found)
    row = {
        "conversation_id": session,
        "migrated": migrated,
        "records": records,
        "skeletons": skeletons,
        "kept": kept,
    }
    return canonical(row) + "\n"


def enable(home: Path) -> None:
    (home / ".records").mkdir(parents=True)
    (home / ".records" / "format").write_text('{"neosian_records":1}\n')


def answers(binary: Binary) -> dict[str, Any]:
    """What a client reads and finds, whatever form the turns are stored in."""
    with serve(binary) as server:
        read = server.post("conversation/read_turns", conversation_id=SESSION)
        found = {
            query: server.post("conversation/search_turns", query=query, limit=10)
            for query in ["first", "héllo", "a.txt", "files", "spaced", "nothing"]
        }
    return {"read": read, "found": found}


def test_migrate_rewrites_whole_turns_as_records_and_keeps_every_other_row(
    binary: Binary,
) -> None:
    spaced = json.dumps(whole(4, "spaced")) + "\n"
    noted = ascii_line(whole(5, "noted", note="written by hand"))
    kept = ascii_line(SKELETON) + spaced + noted
    conversation = binary.home / "conversations" / SESSION
    conversation.mkdir(parents=True)
    log = conversation / "turns.jsonl"
    log.write_text(ascii_line(WHOLE) + ascii_line(TURN_2) + kept, encoding="utf-8")
    enable(binary.home)
    before = answers(binary)
    assert [turn["turn"] for turn in before["read"]["turns"]] == [1, 2, 3, 4, 5]
    assert before["found"]["héllo"]["turns"][0]["messages"] == MESSAGES

    first = binary.run("records", "migrate")
    assert first.returncode == 0, first.stderr
    assert first.stdout == answer(SESSION, 2, 0, skeletons=1, spelling=1, content=1)
    migrated = header(WHOLE, FIRST, SESSION) + header(TURN_2, RECORDS, SESSION)
    assert log.read_text(encoding="utf-8") == migrated + kept
    records = conversation / "records"
    assert (records / "1.jsonl").read_text(encoding="utf-8") == record_line(FIRST[0])
    assert (records / "2.jsonl").read_text(encoding="utf-8") == "".join(
        record_line(item) for item in RECORDS
    )
    assert sorted(path.name for path in conversation.iterdir()) == [
        "records",
        "turns.jsonl",
    ]
    assert answers(binary) == before

    again = binary.run(
        "records", "migrate", "--conversation", SESSION, "--conversation", SESSION
    )
    assert again.returncode == 0, again.stderr
    assert again.stdout == answer(SESSION, 0, 2, skeletons=1, spelling=1, content=1)
    assert log.read_text(encoding="utf-8") == migrated + kept
    assert answers(binary) == before


def test_a_named_migration_checks_every_name_before_it_touches_a_conversation(
    binary: Binary,
) -> None:
    """A stopped migration of another conversation stays as it stopped."""
    enable(binary.home)
    done = binary.home / "conversations" / SESSION
    done.mkdir(parents=True)
    (done / "turns.jsonl").write_text(ascii_line(WHOLE), encoding="utf-8")
    waiting = binary.home / "conversations" / "c-wait"
    pending = waiting / ".migrate-pending"
    (pending / "records").mkdir(parents=True)
    (waiting / "turns.jsonl").write_text(ascii_line(WHOLE), encoding="utf-8")
    staged = header(WHOLE, FIRST, "c-wait")
    (pending / "turns.jsonl").write_text(staged, encoding="utf-8")
    (pending / "records" / "1.jsonl").write_text(record_line(FIRST[0]))

    for name, why in [
        ("c-none", "no conversation c-none in this store; nothing was migrated"),
        (SESSION.upper(), f"no conversation {SESSION.upper()} in this store"),
        ("../x", "agent_conversation_id_invalid"),
    ]:
        refused = binary.run(
            "records", "migrate", "--json", "--conversation", SESSION,
            "--conversation", name,
        )  # fmt: skip
        assert refused.returncode == 1, refused.stderr
        assert why in json.loads(refused.stdout)["error"]
        assert (done / "turns.jsonl").read_text() == ascii_line(WHOLE)
        assert (waiting / "turns.jsonl").read_text() == ascii_line(WHOLE)
        assert (pending / "turns.jsonl").read_text() == staged
        assert not (done / "records").exists()
    assert not (binary.home / "conversations" / "c-none").exists()

    finished = binary.run("records", "migrate", "--conversation", "c-wait")
    assert finished.returncode == 0, finished.stderr
    assert finished.stdout == answer("c-wait", 0, 1)
    assert (waiting / "turns.jsonl").read_text() == staged
    assert (waiting / "records" / "1.jsonl").read_text() == record_line(FIRST[0])
    assert not pending.exists()
    assert (done / "turns.jsonl").read_text() == ascii_line(WHOLE)

    every = binary.run("records", "migrate")
    assert every.returncode == 0, every.stderr
    assert every.stdout == answer(SESSION, 1, 0) + answer("c-wait", 0, 1)


def test_migrate_refuses_a_store_it_cannot_migrate(binary: Binary) -> None:
    conversation = binary.home / "conversations" / SESSION
    conversation.mkdir(parents=True)
    log = conversation / "turns.jsonl"
    log.write_text(ascii_line(WHOLE), encoding="utf-8")
    plain = binary.run("records", "migrate", "--json")
    assert plain.returncode == 1, plain.stderr
    assert "records are not enabled on this store" in json.loads(plain.stdout)["error"]
    missing = binary.directory / "absent"
    absent = binary.run("records", "migrate", "--root", str(missing), "--json")
    assert absent.returncode == 1, absent.stderr
    assert f"no store at {missing}" in json.loads(absent.stdout)["error"]
    assert not missing.exists()
    for extra, flags in [
        ({"NEOSIAN_POSTGRES_DSN": "postgresql://nobody@127.0.0.1:9/none"}, []),
        ({"NEOSIAN_CLIENT_TOKEN": "t"}, ["--url", "http://127.0.0.1:9"]),
    ]:
        other = subprocess.run(
            [str(binary.executable), "records", "migrate", *flags],
            capture_output=True,
            text=True,
            env={**binary.environment(), **extra},
            cwd=binary.directory,
            timeout=30,
            check=False,
        )
        assert other.returncode == 1, other.stderr
        assert "records migrate requires a FileStore" in other.stderr
    assert log.read_text(encoding="utf-8") == ascii_line(WHOLE)
    assert sorted(path.name for path in conversation.iterdir()) == ["turns.jsonl"]
