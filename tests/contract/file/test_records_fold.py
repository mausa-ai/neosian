"""`neosian records fold` on a FileStore (DESIGN §40.54 item 21, T1b2c4).

The logs, the records, the seal's receipt and the pending work are written
here by hand from the design, and so is every byte a fold must leave.
Nothing is generated by the binary under test.
"""

import hashlib
import json
import shutil
import subprocess
from pathlib import Path

from tests.contract.file.test_records import (
    RECORDS,
    SESSION,
    WHOLE,
    canonical,
    header,
    plant,
    record,
    record_line,
)
from tests.contract.file.test_records_migrate import (
    BARE,
    NESTED,
    SKELETON,
    TURN_2,
    answers,
    ascii_line,
    enable,
    whole,
)
from tests.contract.support import Binary, serve

DRAFT = "d7c1e0b2a9f44e57"


def answer(session: str, folded: int, whole: int, **found: int) -> str:
    row = {
        "conversation_id": session,
        "folded": folded,
        "whole": whole,
        "skeletons": found.get("skeletons", 0),
        "drafts": found.get("drafts", 0),
        "restores": found.get("restores", 0),
    }
    return canonical(row) + "\n"


def names(directory: Path) -> list[str]:
    return sorted(path.name for path in directory.iterdir())


def test_a_fold_after_a_migration_gives_the_first_log_back_byte_for_byte(
    binary: Binary,
) -> None:
    spaced = json.dumps(whole(4, "spaced")) + "\n"
    noted = ascii_line(whole(5, "noted", note="written by hand"))
    first = ascii_line(WHOLE) + ascii_line(TURN_2) + ascii_line(SKELETON)
    first += spaced + noted + ascii_line(BARE) + ascii_line(NESTED)
    conversation = binary.home / "conversations" / SESSION
    conversation.mkdir(parents=True)
    log = conversation / "turns.jsonl"
    log.write_text(first, encoding="utf-8")
    enable(binary.home)
    before = answers(binary)
    assert binary.run("records", "migrate").returncode == 0
    assert log.read_text(encoding="utf-8") != first

    folded = binary.run("records", "fold")
    assert folded.returncode == 0, folded.stderr
    assert folded.stdout == answer(SESSION, 2, 4, skeletons=1)
    assert log.read_text(encoding="utf-8") == first
    assert names(conversation) == ["turns.jsonl"]
    assert answers(binary) == before
    again = binary.run("records", "fold", "--conversation", SESSION, "--json")
    assert again.returncode == 0, again.stderr
    assert again.stdout == answer(SESSION, 0, 6, skeletons=1)

    # The documented way back: no marker, and the store reads as before.
    shutil.rmtree(binary.home / ".records")
    assert answers(binary) == before
    assert log.read_text(encoding="utf-8") == first


def test_a_fold_makes_a_records_turn_whole_and_keeps_its_seals_digests(
    binary: Binary,
) -> None:
    plant(binary.home, RECORDS)
    conversation = binary.home / "conversations" / SESSION
    sealed = ascii_line(header(2, RECORDS))
    (conversation / ".drafts").mkdir()
    (conversation / ".drafts" / f"{DRAFT}.sealed").write_text(sealed)
    with serve(binary) as server:
        before = server.post("conversation/read_turns", conversation_id=SESSION)

    folded = binary.run("records", "fold")
    assert folded.returncode == 0, folded.stderr
    assert folded.stdout == answer(SESSION, 1, 1)
    log = (conversation / "turns.jsonl").read_text(encoding="utf-8")
    assert log == ascii_line(WHOLE) + ascii_line(TURN_2)
    assert names(conversation) == [".drafts", "turns.jsonl"]
    assert names(conversation / ".drafts") == [f"{DRAFT}.sealed", "folded"]
    assert (conversation / ".drafts" / f"{DRAFT}.sealed").read_text() == sealed
    owner = {"neosian_format": 1, "draft": DRAFT, "turn": 2, "records": 4}
    digests = [hashlib.sha256(canonical(item).encode()).hexdigest() for item in RECORDS]
    receipt = canonical(owner) + "\n" + "".join(digest + "\n" for digest in digests)
    assert (conversation / ".drafts" / "folded" / "2").read_text() == receipt
    with serve(binary) as server:
        after = server.post("conversation/read_turns", conversation_id=SESSION)
        assert after == before
        server.post("conversation/redact_turns", conversation_id=SESSION, turns=[2])
    assert names(conversation / ".drafts") == ["folded"]
    assert names(conversation / ".drafts" / "folded") == []


def test_pending_work_refuses_a_fold_until_it_is_discarded_on_request(
    binary: Binary,
) -> None:
    enable(binary.home)
    conversation = binary.home / "conversations" / SESSION
    drafts = conversation / ".drafts"
    drafts.mkdir(parents=True)
    log = conversation / "turns.jsonl"
    log.write_text(ascii_line(WHOLE), encoding="utf-8")
    (drafts / "open.state").write_bytes(b"{")
    line = record_line(record(0, 0, "user", "prompt", "open"))
    (drafts / "open.jsonl").write_text(line, encoding="utf-8")
    alone = binary.home / "conversations" / "c-only" / ".drafts"
    alone.mkdir(parents=True)
    (alone / "left.state").write_bytes(b"{")
    staged = binary.home / ".records" / "restore" / "c-wait" / "backup"
    staged.mkdir(parents=True)
    (staged / "state").write_bytes(b"{")

    for name, why in [
        (SESSION, f"conversation {SESSION} holds pending work (1 open drafts, 0 st"),
        ("c-wait", "conversation c-wait holds pending work (0 open drafts, 1 st"),
        ("c-none", "no conversation c-none in this store; nothing was folded"),
        (SESSION.upper(), f"no conversation {SESSION.upper()} in this store"),
        ("../x", "agent_conversation_id_invalid"),
    ]:
        refused = binary.run("records", "fold", "--json", "--conversation", name)
        assert refused.returncode == 1, refused.stderr
        assert why in json.loads(refused.stdout)["error"]
        assert (drafts / "open.jsonl").read_text(encoding="utf-8") == line
        assert (staged / "state").read_bytes() == b"{"
        assert (alone / "left.state").read_bytes() == b"{"
    assert not (binary.home / "conversations" / "c-wait").exists()

    every = binary.run("records", "fold", "--discard-pending")
    assert every.returncode == 0, every.stderr
    assert every.stdout == (
        answer("c-only", 0, 0, drafts=1)
        + answer(SESSION, 0, 1, drafts=1)
        + answer("c-wait", 0, 0, restores=1)
    )
    assert not (drafts / "open.state").exists()
    assert not (drafts / "open.jsonl").exists()
    assert not (alone / "left.state").exists()
    assert not (binary.home / ".records" / "restore" / "c-wait").exists()
    assert not (binary.home / "conversations" / "c-wait").exists()
    assert log.read_text(encoding="utf-8") == ascii_line(WHOLE)


def test_fold_refuses_a_store_it_cannot_fold(binary: Binary) -> None:
    conversation = binary.home / "conversations" / SESSION
    conversation.mkdir(parents=True)
    log = conversation / "turns.jsonl"
    log.write_text(ascii_line(WHOLE), encoding="utf-8")
    plain = binary.run("records", "fold", "--json")
    assert plain.returncode == 1, plain.stderr
    assert "records are not enabled on this store" in json.loads(plain.stdout)["error"]
    missing = binary.directory / "absent"
    absent = binary.run("records", "fold", "--root", str(missing), "--json")
    assert absent.returncode == 1, absent.stderr
    assert f"no store at {missing}" in json.loads(absent.stdout)["error"]
    assert not missing.exists()
    dsn = "postgresql://nobody@127.0.0.1:9/none"
    for extra, flags, why in [
        ({"NEOSIAN_POSTGRES_DSN": dsn}, [], "Postgres request failed"),
        (
            {"NEOSIAN_CLIENT_TOKEN": "t"},
            ["--url", "http://127.0.0.1:9"],
            "records fold requires a FileStore",
        ),
    ]:
        other = subprocess.run(
            [str(binary.executable), "records", "fold", *flags],
            capture_output=True,
            text=True,
            env={**binary.environment(), **extra},
            cwd=binary.directory,
            timeout=30,
            check=False,
        )
        assert other.returncode == 1, other.stderr
        assert why in other.stderr
        assert dsn not in other.stdout + other.stderr
    assert log.read_text(encoding="utf-8") == ascii_line(WHOLE)
    assert names(conversation) == ["turns.jsonl"]
