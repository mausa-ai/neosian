"""`conversation/search_records` and `store/sweep_records` over raw HTTP,
written from DESIGN §40.54 items 8.2, 11 and 13 with no product code.

A hit is built here from the record that was written and its turn's header,
key by key in item 11's order, and its excerpt by memory search's rule: at
most 240 scalars starting up to 40 before the first match. Scores are
literals in the tests, from an independent Python reference of memory
ranking version 1's formula, never generated by the binary under test.
"""

from __future__ import annotations

import base64
import json
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import Any
from urllib.error import HTTPError
from urllib.request import ProxyHandler, Request, build_opener

from tests.contract.records.support import compact
from tests.contract.support import Reply, Server

SEARCH = "conversation/search_records"
SWEEP = "store/sweep_records"
HIT_KEYS = [
    "conversation_id",
    "turn",
    "seq",
    "message",
    "kind",
    "call_id",
    "name",
    "created_at",
    "actor",
    "size",
    "excerpt",
]
SWEPT_KEYS = ["conversation_id", "drafts", "restores", "freed_bytes"]
SEARCHABLE = ["prompt", "reply", "system", "tool_result", "tool_call"]
WHOLE_STORE = "this token's allowance does not reach the whole store"
UNGRANTED = (
    "this token's allowance does not reach"
    " the requested operation under this client's grants"
)
ABSENT = {
    "code": "agent_configuration_error",
    "message": "records are not enabled on this store; run `neosian records enable`",
    "details": {},
}


def post(server: Server, route: str, body: Any, *, token: str | None = None) -> Reply:
    return server.request("/v1/" + route, body, token=token)


def search(server: Server, query: str, **more: Any) -> dict[str, Any]:
    """One accepted search; request and answer checked against the OpenAPI,
    and the order of every key checked as parsed: `hits`, then `order` only
    when the request named one; `score` last and only under relevance."""
    body: dict[str, Any] = server.post(SEARCH, query=query, **more)
    assert list(body) == (["hits", "order"] if "order" in more else ["hits"])
    scored = more.get("order") == "relevance"
    for found in body["hits"]:
        assert list(found) == (HIT_KEYS + ["score"] if scored else HIT_KEYS)
        assert list(found["excerpt"]) == ["offset", "text"]
        assert len(found["excerpt"]["text"]) <= 240
    return body


def sweep(server: Server, **body: Any) -> dict[str, Any]:
    """One accepted sweep, its keys in item 13's order."""
    page: dict[str, Any] = server.post(SWEEP, **body)
    assert list(page) == ["conversations", "next_cursor", "write"]
    for one in page["conversations"]:
        assert list(one) == SWEPT_KEYS
    assert page["write"] is body.get("write", False)
    return page


def refusal(
    server: Server,
    route: str,
    body: Any,
    status: int = 400,
    code: str = "value_error",
    *,
    token: str | None = None,
) -> dict[str, Any]:
    """A refusal's envelope, its three keys exactly."""
    reply = post(server, route, body, token=token)
    assert reply.status == status, reply
    assert list(reply.body) == ["error"], reply
    error: dict[str, Any] = reply.body["error"]
    assert list(error) == ["code", "message", "details"], reply
    assert error["code"] == code, reply
    return error


def message(server: Server, route: str, body: Any) -> str:
    """The message of a `400 value_error` with empty details."""
    error = refusal(server, route, body)
    assert error["details"] == {}
    return str(error["message"])


def forbidden(server: Server, route: str, body: Any, token: str) -> str:
    """The message of a `403 forbidden` with empty details."""
    error = refusal(server, route, body, 403, "forbidden", token=token)
    assert error["details"] == {}
    return str(error["message"])


def raw(server: Server, route: str, body: Any) -> tuple[int, bytes]:
    """The status and the answer's bytes as sent."""
    request = Request(
        f"{server.url}/v1/{route}",
        data=json.dumps(body).encode(),
        headers={"Authorization": f"Bearer {server.token}"},
        method="POST",
    )
    try:
        response = build_opener(ProxyHandler({})).open(request, timeout=30)
    except HTTPError as error:
        response = error
    with response:
        data: bytes = response.read()
        assert response.headers["Content-Length"] == str(len(data))
        return response.status, data


def excerpt(text: str, terms: list[str]) -> dict[str, Any]:
    """Memory search's window over a record's text: `offset` in scalars,
    up to 40 before the first match of any term, then at most 240 scalars;
    from the start when no term is in the text (a call matched on its name).
    The texts of these contracts fold scalar for scalar."""
    folded = text.lower()
    assert len(folded) == len(text)
    found = [folded.find(term.lower()) for term in terms]
    first = min((at for at in found if at >= 0), default=0)
    offset = max(first - 40, 0)
    return {"offset": offset, "text": text[offset : offset + 240]}


def hit(
    conversation: str,
    turn: dict[str, Any],
    item: dict[str, Any],
    terms: list[str],
    *,
    name: str | None = None,
    score: int | None = None,
) -> dict[str, Any]:
    """The hit a written record makes, from its turn's header (`turn`,
    `created_at`, `actor`), in item 11's key order. A call carries its own
    name; a tool result is given its call's by the caller."""
    found = {
        "conversation_id": conversation,
        "turn": turn["turn"],
        "seq": item["seq"],
        "message": item["message"],
        "kind": item["kind"],
        "call_id": item["call_id"],
        "name": item["name"] if item["kind"] == "tool_call" else name,
        "created_at": turn["created_at"],
        "actor": turn["actor"],
        "size": item["size"],
        "excerpt": excerpt(item["text"], terms),
    }
    if score is not None:
        found["score"] = score
    return found


def places(body: dict[str, Any]) -> list[tuple[str, int, int]]:
    return [(h["conversation_id"], h["turn"], h["seq"]) for h in body["hits"]]


def ranked(body: dict[str, Any]) -> list[tuple[int, int, int]]:
    """Each hit's turn, seq and score, in answer order."""
    return [(h["turn"], h["seq"], h["score"]) for h in body["hits"]]


def answer_bytes(hits: list[Any], order: str | None = None) -> bytes:
    """A search answer as item 11 orders it."""
    return compact({"hits": hits} if order is None else {"hits": hits, "order": order})


def cursor(*parts: Any) -> str:
    """A cursor as the cursor codec spells one: URL-safe base64 of a compact
    JSON list, the method first."""
    text = json.dumps(list(parts), separators=(",", ":"))
    return base64.urlsafe_b64encode(text.encode()).decode()


@contextmanager
def store_lock(home: Path) -> Iterator[None]:
    """The FileStore's advisory lock, held as another local process holds
    it: every store operation waits while this is held."""
    import fcntl

    home.mkdir(parents=True, exist_ok=True)
    with open(home / ".store.lock", "a+b") as file:
        fcntl.flock(file, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(file, fcntl.LOCK_UN)
