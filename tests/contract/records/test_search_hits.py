"""`conversation/search_records`, its answer (DESIGN §40.54 item 11): both
orders with literal scores, `kinds`, the time bounds, `limit`, a hit's keys
in the raw bytes, the excerpt and its offset in scalars, a tool result
naming its call, and the turns stored whole searched as the same records.

Expected scores are literal values from an independent Python reference of
the pinned formula, never generated by the binary under test."""

from __future__ import annotations

import json
from typing import Any

from tests.contract.records.searching import (
    SEARCH,
    SEARCHABLE,
    answer_bytes,
    excerpt,
    hit,
    places,
    ranked,
    raw,
    search,
)
from tests.contract.records.support import enable, record, write
from tests.contract.support import Binary, Server, serve

SESSION = "s-find"
TERMS = ["cache", "deploy"]
WHOLE = [
    record(0, 0, "user", "prompt", "Deploy the cache service"),
    record(1, 1, "assistant", "reply", "cache deploy started; deploy window is Friday"),
]
PARTS = [
    record(0, 0, "system", "system", "You deploy carefully."),
    record(1, 1, "user", "prompt", "check the cache"),
    record(
        2,
        2,
        "assistant",
        "tool_call",
        '{"target":"cache"}',
        content="none",
        call=0,
        call_id="c1",
        name="deploy_cache",
    ),
    record(3, 2, "assistant", "reasoning", '{"summary":"deploy cache"}', content=None),
    record(4, 3, "tool", "tool_result", "cache ok\ndeploy ok", call_id="c1"),
    record(5, 4, "assistant", "reply", "All good."),
]
# (turn, seq, score) under relevance for "deploy CACHE", from the reference.
ALL_FIVE = [
    (2, 4, 549467),
    (2, 2, 535557),
    (1, 0, 495486),
    (1, 1, 457983),
    (2, 1, 290561),
    (2, 0, 260541),
]


def corpus(server: Server) -> tuple[dict[str, Any], dict[str, Any]]:
    """Turn 1 stored whole by `append_turn`, turn 2 written as records;
    each turn's header."""
    server.post(
        "conversation/append_turn",
        conversation_id=SESSION,
        messages=[
            {"role": "user", "content": WHOLE[0]["text"]},
            {"role": "assistant", "content": WHOLE[1]["text"]},
        ],
    )
    stored = server.post("conversation/read_turns", conversation_id=SESSION)
    second: dict[str, Any] = write(server, SESSION, "d", PARTS, seal=True, actor="me")
    return stored["turns"][0], second["turn"]


def test_newest_answers_records_holding_every_term(records: Server) -> None:
    first, second = corpus(records)
    assert (first["actor"], second["actor"]) == (
        "client:contract",
        "client:contract/me",
    )
    # A call is matched on its name too, and a tool result names its call.
    expected = [
        hit(SESSION, second, PARTS[2], TERMS),
        hit(SESSION, second, PARTS[4], TERMS, name="deploy_cache"),
        hit(SESSION, first, WHOLE[0], TERMS),
        hit(SESSION, first, WHOLE[1], TERMS),
    ]
    assert expected[0]["name"] == "deploy_cache"
    assert expected[1]["excerpt"] == {"offset": 0, "text": "cache ok\ndeploy ok"}
    assert search(records, "deploy CACHE") == {"hits": expected}
    named = search(records, "cache deploy", order="newest", conversations=[SESSION])
    assert named == {"hits": expected, "order": "newest"}
    # The raw bytes: every key in item 11's order, nothing between.
    assert raw(records, SEARCH, {"query": "deploy CACHE"}) == (
        200,
        answer_bytes(expected),
    )
    assert raw(records, SEARCH, {"query": "deploy CACHE", "order": "newest"}) == (
        200,
        answer_bytes(expected, "newest"),
    )
    # A call's name is the call's alone: its result is not matched on it.
    by_name = search(records, "DEPLOY_cache")
    assert by_name == {"hits": [hit(SESSION, second, PARTS[2], ["deploy_cache"])]}
    assert by_name["hits"][0]["excerpt"] == {"offset": 0, "text": '{"target":"cache"}'}
    # A kind that is not searchable holds no hit, whatever it says.
    assert search(records, "summary") == {"hits": []}


def test_relevance_scores_records_holding_a_term_with_literal_scores(
    records: Server,
) -> None:
    first, second = corpus(records)
    headers = {1: first, 2: second}
    items = {1: WHOLE, 2: PARTS}
    names = {(2, 4): "deploy_cache"}

    def expect(rows: list[tuple[int, int, int]]) -> list[dict[str, Any]]:
        return [
            hit(
                SESSION,
                headers[turn],
                items[turn][seq],
                TERMS,
                name=names.get((turn, seq)),
                score=score,
            )
            for turn, seq, score in rows
        ]

    body = {"query": "deploy CACHE", "order": "relevance"}
    answer = search(records, **body)
    assert ranked(answer) == ALL_FIVE
    assert answer == {"hits": expect(ALL_FIVE), "order": "relevance"}
    assert raw(records, SEARCH, body) == (
        200,
        answer_bytes(expect(ALL_FIVE), "relevance"),
    )
    # `score` is the last key of a hit, in the bytes.
    text = raw(records, SEARCH, body)[1].decode()
    assert text.count('"},"score":') == 6 and text.endswith('}],"order":"relevance"}')
    # `limit` cuts the ranking; it does not change the statistics.
    top = search(records, "deploy CACHE", order="relevance", limit=2)
    assert ranked(top) == ALL_FIVE[:2]
    # `kinds` selects the candidates, so the statistics follow it.
    assert ranked(
        search(records, "deploy CACHE", order="relevance", kinds=["reply", "prompt"])
    ) == [(1, 1, 658961), (1, 0, 640996), (2, 1, 164840)]
    assert ranked(search(records, "cache", order="relevance", kinds=["tool_call"])) == [
        (2, 2, 395563)
    ]
    explicit = search(
        records, "deploy CACHE", order="relevance", kinds=list(reversed(SEARCHABLE))
    )
    assert ranked(explicit) == ALL_FIVE
    assert search(records, "deploy", order="relevance", kinds=[]) == {
        "hits": [],
        "order": "relevance",
    }


def test_since_and_before_bound_the_turns_time_in_both_orders(
    records: Server,
) -> None:
    """`since` is inclusive and `before` exclusive, compared with the
    turn's `created_at`; under relevance the candidates are those inside."""
    first, second = corpus(records)
    old, new = first["created_at"], second["created_at"]
    assert old < new and old.endswith("Z") and new.endswith("Z")
    later = [(SESSION, 2, 2), (SESSION, 2, 4)]
    earlier = [(SESSION, 1, 0), (SESSION, 1, 1)]
    assert places(search(records, "deploy cache", since=new)) == later
    assert places(search(records, "deploy cache", before=new)) == earlier
    assert places(search(records, "deploy cache", since=old, before=new)) == earlier
    assert places(search(records, "deploy cache", since=old)) == later + earlier
    assert places(search(records, "deploy cache", before=old)) == []
    assert places(search(records, "deploy cache", since="2100-01-01T00:00:00Z")) == []
    wide = search(
        records,
        "deploy cache",
        since="2000-01-01T00:00:00Z",
        before="2100-01-01T00:00:00.000001Z",
    )
    assert places(wide) == later + earlier
    assert ranked(search(records, "deploy cache", order="relevance", since=new)) == [
        (2, 4, 760961),
        (2, 2, 734682),
        (2, 1, 405460),
        (2, 0, 358400),
    ]
    assert ranked(search(records, "deploy cache", order="relevance", before=new)) == [
        (1, 0, 416500),
        (1, 1, 393060),
    ]


def test_limit_is_a_bound_and_the_route_does_not_page(records: Server) -> None:
    items = [
        record(index, index, "user", "prompt", f"needle {index}")
        for index in range(120)
    ]
    write(records, "s-many", "d", items, seal=True)
    default = search(records, "needle")
    assert list(default) == ["hits"]
    assert [found["seq"] for found in default["hits"]] == list(range(20))
    assert len(search(records, "needle", limit=100)["hits"]) == 100
    assert [found["seq"] for found in search(records, "needle", limit=3)["hits"]] == [
        0,
        1,
        2,
    ]
    # Ten records are one scalar shorter than the rest and tie at the top;
    # ties are answered in newest order, which inside a turn is `seq`.
    best = search(records, "needle", order="relevance", limit=12)
    assert ranked(best) == [(1, seq, 4353) for seq in range(10)] + [
        (1, 10, 4156),
        (1, 11, 4156),
    ]
    assert len(search(records, "needle", order="relevance")["hits"]) == 20


def whole(turn: int, text: str) -> dict[str, Any]:
    return {
        "neosian_format": 1,
        "turn": turn,
        "created_at": "2026-11-21T10:00:00Z",
        "messages": [
            {
                "role": "user",
                "content": text,
                "reasoning": None,
                "tool_calls": [],
                "tool_call_id": None,
            }
        ],
        "actor": None,
    }


def test_turns_of_one_instant_are_ordered_by_conversation_then_turn(
    binary: Binary,
) -> None:
    """Item 11's newest order past the time: conversation id descending,
    turn descending, `seq` ascending; relevance ties follow it. Three turns
    stored whole, planted here by hand at the same instant."""
    enable(binary)
    for conversation, turns in [("t-a", [1, 2]), ("t-b", [1])]:
        directory = binary.home / "conversations" / conversation
        directory.mkdir(parents=True)
        rows = [whole(turn, "same words") for turn in turns]
        log = "".join(json.dumps(row, separators=(",", ":")) + "\n" for row in rows)
        (directory / "turns.jsonl").write_text(log, encoding="utf-8")
    order = [("t-b", 1, 0), ("t-a", 2, 0), ("t-a", 1, 0)]
    with serve(binary) as server:
        newest = search(server, "same")
        assert places(newest) == order
        assert newest["hits"][0] == {
            "conversation_id": "t-b",
            "turn": 1,
            "seq": 0,
            "message": 0,
            "kind": "prompt",
            "call_id": None,
            "name": None,
            "created_at": "2026-11-21T10:00:00Z",
            "actor": None,
            "size": 10,
            "excerpt": {"offset": 0, "text": "same words"},
        }
        tied = search(server, "same", order="relevance")
        assert places(tied) == order
        assert [found["score"] for found in tied["hits"]] == [133531] * 3
        assert places(search(server, "same", conversations=["t-a"])) == order[1:]


def test_an_excerpt_is_240_scalars_and_its_offset_counts_scalars(
    records: Server,
) -> None:
    """Up to 40 scalars before the first match, at most 240 in all, the
    offset in scalars of the record's text: not bytes, not UTF-16 units."""
    accents = "é" * 100 + "日本" + " Needle " + "x" * 300
    faces = "\U0001f600" * 50 + "needle" + "\U0001f600" * 300
    texts = [
        accents,
        faces,
        "the needle is near the start",
        "y" * 40 + "NEEDLE" + "z" * 500,
        "y" * 41 + "nEEdle",
        "école " * 20 + "ÉCOLE needle",
    ]
    items = [
        record(index, index, "user", "prompt", text) for index, text in enumerate(texts)
    ]
    sealed = write(records, "s-scalars", "d", items, seal=True)
    found = search(records, "NEEDLE")
    assert found == {
        "hits": [hit("s-scalars", sealed["turn"], item, ["needle"]) for item in items]
    }
    excerpts = [one["excerpt"] for one in found["hits"]]
    assert excerpts[0] == {"offset": 63, "text": accents[63:303]}
    assert len(accents[:63].encode()) == 126 and len(excerpts[0]["text"]) == 240
    assert excerpts[1] == {"offset": 10, "text": faces[10:250]}
    assert len(excerpts[1]["text"].encode()) == 4 * 234 + 6
    assert excerpts[2] == {"offset": 0, "text": "the needle is near the start"}
    assert excerpts[3]["offset"] == 0 and len(excerpts[3]["text"]) == 240
    assert excerpts[4] == {"offset": 1, "text": "y" * 40 + "nEEdle"}
    # The first match of any term places the window, and terms fold.
    both = search(records, "needle École")
    assert both["hits"] == [hit("s-scalars", sealed["turn"], items[5], ["école"])]
    assert both["hits"][0]["excerpt"]["offset"] == 0
    assert excerpt("a" * 50 + "b", ["b"]) == {"offset": 10, "text": "a" * 40 + "b"}


def test_a_tool_result_names_its_call_or_null(records: Server) -> None:
    """`name` on a tool result is the name of the call with its `call_id`
    in the same turn; null when the turn holds none. Its own `name` field
    is null in the record."""
    items = [
        record(
            0,
            0,
            "assistant",
            "tool_call",
            '{"path":"a"}',
            content="none",
            call=0,
            call_id="c1",
            name="Read",
        ),
        record(
            1,
            0,
            "assistant",
            "tool_call",
            '{"path":"b"}',
            content=None,
            call=1,
            call_id="c2",
            name="Grep",
        ),
        record(2, 1, "tool", "tool_result", "needle from b", call_id="c2"),
        record(3, 2, "tool", "tool_result", "needle from a", call_id="c1"),
        record(4, 3, "tool", "tool_result", "needle from nowhere", call_id="c9"),
    ]
    sealed = write(records, "s-calls", "d", items, seal=True)
    assert all(item["name"] is None for item in items[2:])
    found = search(records, "needle", kinds=["tool_result"])
    assert found["hits"] == [
        hit("s-calls", sealed["turn"], items[2], ["needle"], name="Grep"),
        hit("s-calls", sealed["turn"], items[3], ["needle"], name="Read"),
        hit("s-calls", sealed["turn"], items[4], ["needle"], name=None),
    ]
    assert [one["call_id"] for one in found["hits"]] == ["c2", "c1", "c9"]
    ranked_too = search(records, "needle", kinds=["tool_result"], order="relevance")
    assert {one["seq"]: one["name"] for one in ranked_too["hits"]} == {
        2: "Grep",
        3: "Read",
        4: None,
    }
