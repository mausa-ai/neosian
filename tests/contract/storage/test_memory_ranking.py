"""Optional memory ranking v1: orders and date bounds over memory search.

Expected scores are literal values from an independent Python reference of the
pinned formula (DESIGN §40.41), never generated by the binary under test.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta
from typing import Any

import pytest

from tests.contract.storage.support import Storage, refused

DEPLOY = {
    "notes/deploy": "Deploy window is Friday. Deploy after review.",
    "notes/review": "Review the deploy checklist.",
    "notes/lunch": "Lunch is at noon.",
    "skills/release": "Release steps: tag, deploy, announce.",
}


@pytest.fixture(autouse=True)
def ranking_capability(storage: Storage) -> None:
    capability = storage.capabilities.get("memory_ranking")
    if capability is None:
        pytest.skip("service does not declare optional memory-ranking version 1")
    assert capability == {"version": 1}
    assert storage.capabilities.get("memory_search") == {"version": 1}


def search(storage: Storage, query: str, **body: Any) -> Any:
    return storage.memory("search", query=query, **body)


def ranked(page: Any) -> list[tuple[str, int]]:
    return [(hit["path"], hit["score"]) for hit in page["hits"]]


def test_relevance_scores_are_pinned_and_echoed(storage: Storage) -> None:
    for path, content in DEPLOY.items():
        storage.memory("write", path=path, content=content)
    page = search(storage, "deploy REVIEW", order="relevance")
    assert page["order"] == "relevance" and page["next_cursor"] is None
    assert ranked(page) == [
        ("notes/review", 1348537),
        ("notes/deploy", 1145519),
        ("skills/release", 334880),
    ]
    assert page["hits"][0]["excerpt"]["text"] == DEPLOY["notes/review"]
    assert ranked(search(storage, "deploy REVIEW", order="relevance", limit=1)) == [
        ("notes/review", 1348537)
    ]


def test_relevance_needs_one_term_and_ties_go_to_path(storage: Storage) -> None:
    for path, content in {
        "both": "red blue",
        "red": "red only",
        "none": "green",
    }.items():
        storage.memory("write", path=path, content=content)
    page = search(storage, "red blue", fields=["content"], order="relevance")
    assert ranked(page) == [("both", 1370726), ("red", 444053)]
    assert page["hits"][1]["matched_fields"] == ["content"]
    assert [h["path"] for h in search(storage, "red blue")["hits"]] == ["both"]
    for path in ["tie-b", "tie-a"]:
        storage.memory("write", path=path, content="same words")
    tied = search(storage, "same", fields=["content"], order="relevance")
    assert [h["path"] for h in tied["hits"]] == ["tie-a", "tie-b"]
    assert tied["hits"][0]["score"] == tied["hits"][1]["score"]


def test_statistics_exclude_erased_and_deleted_documents(storage: Storage) -> None:
    for path, content in {"a": "alpha beta", "b": "alpha", "c": "gamma"}.items():
        storage.memory("write", path=path, content=content)
    before = search(storage, "alpha", fields=["content"], order="relevance")
    assert ranked(before) == [("b", 523548), ("a", 390192)]
    storage.memory("redact", path="c")
    after = search(storage, "alpha", fields=["content"], order="relevance")
    assert ranked(after) == [("b", 211109), ("a", 160443)]
    storage.memory("write", path="c", content="gamma")
    storage.memory("delete", path="c")
    assert ranked(search(storage, "alpha", fields=["content"], order="relevance")) == [
        ("b", 211109),
        ("a", 160443),
    ]
    storage.server.post(
        "memory/write", scope=storage.scope + "-other", path="x", content="gamma"
    )
    assert ranked(search(storage, "alpha", fields=["content"], order="relevance")) == [
        ("b", 211109),
        ("a", 160443),
    ]


def test_newest_orders_all_term_matches_by_update_time(storage: Storage) -> None:
    stamps: dict[str, str] = {}
    for path in ["a", "b", "c"]:
        stamps[path] = storage.memory("write", path=path, content="needle pin")[
            "document"
        ]["updated_at"]
    stamps["a"] = storage.memory("write", path="a", content="needle pin again")[
        "document"
    ]["updated_at"]
    storage.memory("write", path="partial", content="needle")
    page = search(storage, "needle pin", order="newest")
    assert page["order"] == "newest" and page["next_cursor"] is None
    expected = sorted(stamps, key=lambda p: (-int_time(stamps[p]), p))
    assert [h["path"] for h in page["hits"]] == expected
    assert all("score" not in h for h in page["hits"])
    assert [
        h["path"]
        for h in search(storage, "needle pin", order="newest", limit=1)["hits"]
    ] == expected[:1]


def int_time(stamp: str) -> int:
    """Exact UTC microseconds, so adjacent writes never swap through float rounding."""
    moment = datetime.fromisoformat(stamp.replace("Z", "+00:00"))
    return (moment - datetime(1970, 1, 1, tzinfo=UTC)) // timedelta(microseconds=1)


def test_date_bounds_apply_in_every_order(storage: Storage) -> None:
    stamps = [
        storage.memory("write", path=path, content="needle")["document"]["updated_at"]
        for path in ["first", "second", "third"]
    ]
    bounds = {"updated_since": stamps[1], "updated_before": stamps[2]}
    for order in [None, "path", "relevance", "newest"]:
        body: dict[str, Any] = dict(bounds)
        if order:
            body["order"] = order
        page = search(storage, "needle", **body)
        assert [h["path"] for h in page["hits"]] == ["second"], order
        assert ("order" in page) == (order is not None)
    assert [
        h["path"]
        for h in search(storage, "needle", updated_since=stamps[2], order="path")[
            "hits"
        ]
    ] == ["third"]


def test_version_1_requests_are_unchanged(storage: Storage) -> None:
    storage.memory("write", path="doc", content="needle")
    page = search(storage, "needle")
    assert set(page) == {"hits", "next_cursor"}
    assert "score" not in page["hits"][0]
    nulls = search(storage, "needle", order=None, updated_since=None)
    assert set(nulls) == {"hits", "next_cursor"}


def test_path_order_cursors_bind_order_and_bounds(storage: Storage) -> None:
    for path in ["a", "b"]:
        storage.memory("write", path=path, content="needle")
    first = search(storage, "needle", order="path", limit=1)
    assert first["order"] == "path" and [h["path"] for h in first["hits"]] == ["a"]
    second = search(
        storage, "needle", order="path", limit=1, cursor=first["next_cursor"]
    )
    assert [h["path"] for h in second["hits"]] == ["b"]
    # A path cursor binds its explicit order and bounds: dropping or changing them refuses.
    base: dict[str, Any] = {"scope": storage.scope, "query": "needle"}
    variants: list[dict[str, Any]] = [
        {},
        {"order": None},
        {"order": "path", "updated_since": "2000-01-01T00:00:00Z"},
    ]
    for changes in variants:
        body = base | changes | {"cursor": first["next_cursor"]}
        refused(storage.server.request("/v1/memory/search", body), "value_error")


@pytest.mark.parametrize(
    "bad",
    [
        {"order": "relevance", "cursor": "anything"},
        {"order": "newest", "cursor": "anything"},
        {"order": "score"},
        {"order": 1},
        {"updated_since": "2026-11-11T10:00:00+01:00"},
        {"updated_before": "yesterday"},
        {"updated_since": 1},
        {
            "updated_since": "2026-11-11T10:00:00Z",
            "updated_before": "2026-11-11T10:00:00Z",
        },
        {
            "updated_since": "2026-11-12T00:00:00Z",
            "updated_before": "2026-11-11T00:00:00Z",
        },
    ],
)
def test_invalid_ranking_requests_refuse(storage: Storage, bad: dict[str, Any]) -> None:
    refused(
        storage.server.request(
            "/v1/memory/search", {"scope": storage.scope, "query": "needle", **bad}
        ),
        "value_error",
    )
