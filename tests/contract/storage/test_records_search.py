TERMS = ["cache", "deploy"]
WHOLE = [
    record(0, 0, "user", "prompt", "Deploy the cache service"),
    record(1, 1, "assistant", "reply", "cache deploy started; deploy window is Friday"),
]
PARTS = [
    record(0, 0, "system", "system", "You deploy carefully."),
    record(1, 1, "user", "prompt", "check the cache"),
    record(
        2,
        2,
        "assistant",
        "tool_call",
        '{"target":"cache"}',
        content="none",
        call=0,
        call_id="c1",
        name="deploy_cache",
    ),
    record(3, 2, "assistant", "reasoning", '{"summary":"deploy cache"}', content=None),
    record(4, 3, "tool", "tool_result", "cache ok\ndeploy ok", call_id="c1"),
    record(5, 4, "assistant", "reply", "All good."),
]
# (turn, seq, score) under relevance for "deploy CACHE", from the reference.
ALL_FIVE = [
    (2, 4, 549467),
    (2, 2, 535557),
    (1, 0, 495486),
    (1, 1, 457983),
    (2, 1, 290561),
    (2, 0, 260541),
]
SPOKEN = [(1, 1, 658961), (1, 0, 640996), (2, 1, 164840)]


@pytest.fixture(autouse=True)
def records_capability(storage: Storage) -> None:
    require_records(storage)


def corpus(storage: Storage) -> tuple[dict[str, Any], dict[str, Any]]:
    """Turn 1 stored whole by `append_turn`, turn 2 written as records;
    each turn's header fields."""
    storage.turns(
        "append_turn",
        messages=[
            {"role": "user", "content": WHOLE[0]["text"]},
            {"role": "assistant", "content": WHOLE[1]["text"]},
        ],
    )
    first = storage.turns("read_turns")["turns"][0]
    second = write(
        storage.server, storage.conversation, "d", PARTS, seal=True, actor="me"
    )
    return first, second["turn"]


def find(storage: Storage, query: str, **more: Any) -> dict[str, Any]:
    return search(storage.server, query, conversations=[storage.conversation], **more)


def test_newest_answers_records_holding_every_term(storage: Storage) -> None:
    session = storage.conversation
    first, second = corpus(storage)
    # A call is matched on its name too, and a tool result names its call.
    expected = [
        hit(session, second, PARTS[2], TERMS),
        hit(session, second, PARTS[4], TERMS, name="deploy_cache"),
        hit(session, first, WHOLE[0], TERMS),
        hit(session, first, WHOLE[1], TERMS),
    ]
    assert expected[0]["name"] == "deploy_cache"
    assert expected[1]["excerpt"] == {"offset": 0, "text": "cache ok\ndeploy ok"}
    assert find(storage, "deploy CACHE") == {"hits": expected}
    assert find(storage, "cache deploy", order="newest") == {
        "hits": expected,
        "order": "newest",
    }
    assert search(storage.peer, "deploy cache", conversations=[session]) == {
        "hits": expected
    }
    # `conversations` is a set, and one that names no conversation holds no hit.
    assert find(storage, "deploy cache")["hits"] == expected
    several = [session + "-absent", session, session]
    assert search(storage.server, "deploy cache", conversations=several) == {
        "hits": expected
    }
    assert search(storage.server, "deploy", conversations=[]) == {"hits": []}
    assert search(storage.server, "deploy", conversations=[session + "-absent"]) == {
        "hits": []
    }
    # A call's name is the call's alone: its result is not matched on it.
    by_name = find(storage, "DEPLOY_cache")
    assert by_name == {"hits": [hit(session, second, PARTS[2], ["deploy_cache"])]}
    assert by_name["hits"][0]["excerpt"] == {"offset": 0, "text": '{"target":"cache"}'}
    # A kind that is not searchable holds no hit, whatever it says.
    assert find(storage, "summary") == {"hits": []}
    # `kinds` narrows, as a set; `limit` bounds, and the route does not page.
    assert places(find(storage, "cache", kinds=["tool_call", "tool_call"])) == [
        (session, 2, 2)
    ]
    assert find(storage, "cache", kinds=[]) == {"hits": []}
    assert find(storage, "deploy cache", kinds=SEARCHABLE)["hits"] == expected
    assert find(storage, "deploy cache", limit=1) == {"hits": expected[:1]}
    assert find(storage, "deploy cache", limit=100) == {"hits": expected}


def test_relevance_scores_records_with_literal_scores(storage: Storage) -> None:
    session = storage.conversation
    first, second = corpus(storage)
    headers = {1: first, 2: second}
    items = {1: WHOLE, 2: PARTS}
    names = {(2, 4): "deploy_cache"}
    expected = [
        hit(
            session,
            headers[turn],
            items[turn][seq],
            TERMS,
            name=names.get((turn, seq)),
            score=score,
        )
        for turn, seq, score in ALL_FIVE
    ]
    answer = find(storage, "deploy CACHE", order="relevance")
    assert ranked(answer) == ALL_FIVE
    assert answer == {"hits": expected, "order": "relevance"}
    # `limit` cuts the ranking; it does not change the statistics.
    top = find(storage, "deploy CACHE", order="relevance", limit=2)
    assert ranked(top) == ALL_FIVE[:2]
    # `kinds` selects the candidates, so the statistics follow it.
    spoken = find(storage, "deploy CACHE", order="relevance", kinds=["reply", "prompt"])
    assert ranked(spoken) == SPOKEN
    assert find(storage, "deploy", order="relevance", kinds=[]) == {
        "hits": [],
        "order": "relevance",
    }


def instant(text: str) -> datetime:
    assert text.endswith("Z"), text
    return datetime.fromisoformat(text.removesuffix("Z") + "+00:00")


def test_since_and_before_bound_the_turns_time(storage: Storage) -> None:
    """`since` is inclusive and `before` exclusive on the turn's time. Two
    turns written one after the other may carry one instant, so the strict
    halves are asserted only when the times differ."""
    first, second = corpus(storage)
    early, late = instant(first["created_at"]), instant(second["created_at"])
    assert early <= late
    cut = second["created_at"]
    everything = {1, 2}

    def turns(**bounds: str) -> set[int]:
        return {place[1] for place in places(find(storage, "cache", **bounds))}

    for order in ("newest", "relevance"):
        later = turns(order=order, since=cut)
        earlier = turns(order=order, before=cut)
        # The second turn is at `cut`: inside `since`, outside `before`.
        assert 2 in later and 2 not in earlier
        if early < late:
            assert (later, earlier) == ({2}, {1})
            assert turns(order=order, since=first["created_at"], before=cut) == {1}
        # Bounds a day around both turns, whatever their instants.
        assert turns(order=order, since="2000-01-01T00:00:00Z") == everything
        assert turns(order=order, before="2999-01-01T00:00:00Z") == everything
        assert turns(order=order, since="2999-01-01T00:00:00Z") == set()
        assert turns(order=order, before="2000-01-01T00:00:00Z") == set()
        between = turns(
            order=order, since="2000-01-01T00:00:00Z", before="2999-01-01T00:00:00Z"
        )
        assert between == everything


def test_an_excerpt_starts_before_the_match_and_the_answer_is_bounded(
    storage: Storage,
) -> None:
    """A long record: the excerpt is 240 scalars starting 40 before the
    first match, `offset` counting from the record's start. The answer as
    read is at most `limit * (16,384 + 6 * u(actor)) + 64` bytes."""
    server, session = storage.server, storage.conversation
    text = "pad " * 500 + "windowneedle " + "tail " * 500
    items = [record(0, 0, "user", "prompt", text)]
    turn = write(server, session, "long", items, seal=True)["turn"]
    expected = hit(session, turn, items[0], ["windowneedle"])
    assert expected["excerpt"] == {"offset": 1_960, "text": text[1_960:2_200]}
    assert find(storage, "windowneedle") == {"hits": [expected]}
    ranked_hit = find(storage, "WINDOWNEEDLE", order="relevance")["hits"][0]
    assert ranked_hit["excerpt"] == expected["excerpt"]
    # Many hits, each with the widest excerpt, under a small and a full limit.
    many = [record(n, n, "user", "prompt", "boundword " + "x" * 400) for n in range(60)]
    write(server, session, "many", many, seal=True)
    actor = len(storage.client.encode())
    for limit, order in [(1, "newest"), (20, "relevance"), (100, "newest")]:
        body = {
            "query": "boundword",
            "conversations": [session],
            "limit": limit,
            "order": order,
        }
        status, sent = answer_bytes(server, SEARCH, body)
        assert status == 200
        hits = json.loads(sent)["hits"]
        assert len(hits) == min(limit, 60)
        assert all(len(found["excerpt"]["text"]) == 240 for found in hits)
        assert len(sent) <= limit * (16_384 + 6 * actor) + 64


def test_a_draft_and_a_redacted_turn_never_match(storage: Storage) -> None:
    storage.require("erasable")
    server, session = storage.server, storage.conversation
    shown = write(server, session, "shown", prompts(1), seal=True)["turn"]
    spoken = [record(0, 0, "user", "prompt", "erasedneedle and more")]
    write(server, session, "erased", spoken, seal=True)
    write(server, session, "open", [record(0, 0, "user", "prompt", "draftneedle")])
    assert places(find(storage, "erasedneedle")) == [(session, 2, 0)]
    assert storage.turns("redact_turns", turns=[2]) == {"count": 1}
    for order in ("newest", "relevance"):
        for query in ("erasedneedle", "draftneedle"):
            assert find(storage, query, order=order)["hits"] == []
    assert find(storage, "a") == {"hits": [hit(session, shown, prompts(1)[0], ["a"])]}
    assert write(server, session, "open", [], discard=True)["state"] == "discarded"


