"""Optional turn records v1: `conversation/search_records` and the preview
of `store/sweep_records`.

A record search answers single records. These cases check both orders with
literal scores, `kinds`, the time bounds, `limit`, a hit's keys, the
excerpt, a tool result naming its call, what never matches, and the
refusals of the request table. Every search names this case's own
conversations, so its statistics hold nothing else. Expected scores are
literal values from an independent Python reference of the pinned formula,
never generated by the service under test. Fixtures are ASCII, where every
backend folds alike.

The sweep is store-wide, so the suite only previews it: every call carries
`write: false` or no `write` at all, and nothing is ever removed. Absent
support is an explicit skip under the full and base profiles.
"""

