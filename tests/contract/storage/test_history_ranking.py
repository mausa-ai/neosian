"""Optional history ranking v1: relevance and turn-time bounds on history search.

Scores are literal values from an independent Python reference of DESIGN
§40.43 (candidate-set statistics, newest-first ties), never generated by the
binary under test. Scored fixtures are ASCII, where every backend folds alike;
non-ASCII cases pin invariants that hold under any backend's case folding.
"""

from __future__ import annotations

from typing import Any

import pytest

from tests.contract.storage.support import Storage, message, refused

DASHBOARD = [
    "The dashboard API response time is 300ms",
    "Lunch at noon today",
    "Dashboard API improved to 250ms after caching",
    "The response time target is 200ms",
]


@pytest.fixture(autouse=True)
def ranking_capability(storage: Storage) -> None:
    capability = storage.capabilities.get("history_ranking")
    if capability is None:
        pytest.skip("service does not declare optional history-ranking version 1")
    assert capability == {"version": 1}


def append(storage: Storage, texts: list[str]) -> list[dict[str, Any]]:
    return [
        storage.turns("append_turn", messages=[message(text)])["turn"] for text in texts
    ]


def search(storage: Storage, query: str, **body: Any) -> Any:
    return storage.server.post(
        "conversation/search_turns",
        query=query,
        conversations=[storage.conversation],
        **body,
    )


def ranked(answer: Any) -> list[tuple[int, int]]:
    return [
        (t["turn"], s) for t, s in zip(answer["turns"], answer["scores"], strict=True)
    ]


def test_relevance_scores_are_pinned_and_echoed(storage: Storage) -> None:
    append(storage, DASHBOARD)
    answer = search(storage, "Dashboard RESPONSE time", order="relevance")
    assert answer["order"] == "relevance"
    assert ranked(answer) == [(1, 1400302), (4, 1006292), (3, 443845)]
    limited = search(storage, "dashboard response time", order="relevance", limit=1)
    assert ranked(limited) == [(1, 1400302)]


def test_candidates_need_one_term_and_ties_go_to_the_newest(storage: Storage) -> None:
    append(storage, ["alpha", "beta", "alpha beta", "same words", "same words"])
    answer = search(storage, "alpha beta", order="relevance")
    assert ranked(answer) == [(3, 760006), (2, 553413), (1, 514297)]
    tied = search(storage, "same", order="relevance")
    assert ranked(tied) == [(5, 182322), (4, 182322)]


def test_newest_and_bounds_keep_version_1_order(storage: Storage) -> None:
    turns = append(storage, DASHBOARD)
    update = turns[2]["created_at"]
    newest = search(storage, "dashboard", order="newest")
    assert newest["order"] == "newest" and "scores" not in newest
    assert [t["turn"] for t in newest["turns"]] == [3, 1]
    cutoff = search(storage, "dashboard", order="relevance", before=update)
    assert [t["turn"] for t in cutoff["turns"]] == [1]
    since = search(storage, "dashboard", since=update)
    assert [t["turn"] for t in since["turns"]] == [3] and "order" not in since
    version_1 = search(storage, "dashboard")
    assert set(version_1) == {"turns"}
    assert [t["turn"] for t in version_1["turns"]] == [3, 1]
    nulls = search(storage, "dashboard", order=None, since=None, before=None)
    assert set(nulls) == {"turns"}


def test_newest_is_the_version_1_answer_within_bounds(storage: Storage) -> None:
    # The only matches differ in non-ASCII case: backends may fold them
    # differently, but newest must still be exactly version 1's answer.
    turns = append(storage, ["élan one", "ÉLAN two", "other words"])
    every = {"since": turns[0]["created_at"], "before": "2999-01-01T00:00:00Z"}
    for limit in [{}, {"limit": 1}]:
        version_1 = search(storage, "élan", **limit)
        assert version_1["turns"], "a backend finds at least the exact-case turn"
        newest = search(storage, "élan", order="newest", **limit)
        assert newest["turns"] == version_1["turns"]
        assert search(storage, "élan", **every, **limit)["turns"] == version_1["turns"]
        bounded = search(storage, "élan", order="newest", **every, **limit)
        assert bounded["turns"] == version_1["turns"]
    # For one term, relevance's candidates are exactly version 1's matches.
    version_1 = search(storage, "élan")["turns"]
    relevance = search(storage, "élan", order="relevance")["turns"]
    assert sorted(t["turn"] for t in relevance) == sorted(t["turn"] for t in version_1)


def test_tool_call_text_matches_alike_in_every_order(storage: Storage) -> None:
    # Searchable text keeps the arguments' recorded key order, whatever the
    # backend stores: 'probe {"aa":"yy","b":"xx"}' then the tool result.
    call = {"id": "call-1", "name": "probe", "arguments": {"aa": "yy", "b": "xx"}}
    messages = [
        {**message(""), "role": "assistant", "content": None, "tool_calls": [call]},
        {**message("probe result"), "role": "tool", "tool_call_id": "call-1"},
    ]
    storage.turns("append_turn", messages=messages)
    query = 'yy","b'
    assert [t["turn"] for t in search(storage, query)["turns"]] == [1]
    newest = search(storage, query, order="newest")
    assert [t["turn"] for t in newest["turns"]] == [1]
    assert ranked(search(storage, query, order="relevance")) == [(1, 287682)]


def test_erased_turns_leave_candidates_and_statistics(storage: Storage) -> None:
    storage.require("erasable")
    append(storage, DASHBOARD)
    storage.turns("redact_turns", actor="erase", turns=[4])
    answer = search(storage, "dashboard response time", order="relevance")
    assert ranked(answer) == [(1, 1607294), (3, 178037)]


@pytest.mark.parametrize(
    "bad",
    [
        {"order": "score"},
        {"order": 1},
        {"since": "2026-11-11T10:00:00+01:00"},
        {"before": "yesterday"},
        {"since": "2026-11-11T10:00:00Z", "before": "2026-11-11T10:00:00Z"},
        {"since": "2026-11-12T00:00:00Z", "before": "2026-11-11T00:00:00Z"},
    ],
)
def test_invalid_ranking_requests_refuse(storage: Storage, bad: dict[str, Any]) -> None:
    refused(
        storage.server.request(
            "/v1/conversation/search_turns",
            {"query": "dashboard", "conversations": [storage.conversation], **bad},
        ),
        "value_error",
    )
