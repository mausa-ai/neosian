"""Optional memory passages v1: matched windows of long values, with headings.

Offsets and headings are literal values from an independent Python reference
of the DESIGN §40.42 rule, never generated by the binary under test.
"""

from __future__ import annotations

from typing import Any

import pytest

from tests.contract.storage.support import Storage, refused

FILLER = "word " * 60
GUIDE = (
    f"# Guide\n{FILLER}deploy once.\n## Release\n"
    f"İ {FILLER}deploy then review the deploy.\n{FILLER}review\n"
)
FENCED = (
    "---\ntitle: t\n# front\n---\n<!-- neosian-knowledge:1\n# header\n-->\n"
    f"# Real\n```\n# Fake\n```\n{FILLER}needle {FILLER}"
)
NOTES = "note " * 60 + "needle in the metadata " + "note " * 10


@pytest.fixture(autouse=True)
def passages_capability(storage: Storage) -> None:
    capability = storage.capabilities.get("memory_passages")
    if capability is None:
        pytest.skip("service does not declare optional memory-passages version 1")
    assert capability == {"version": 1}
    assert storage.capabilities.get("memory_search") == {"version": 1}


def passages(page: Any) -> list[tuple[int, str | None]]:
    return [(p["offset"], p["heading"]) for p in page["hits"][0]["passages"]]


def expected(text: str, offset: int, heading: str | None) -> dict[str, Any]:
    return {
        "field": "content",
        "metadata_key": None,
        "offset": offset,
        "text": text[offset : offset + 240],
        "heading": heading,
    }


def test_windows_follow_distinct_terms_then_occurrences(storage: Storage) -> None:
    storage.memory("write", path="guide", content=GUIDE)
    page = storage.memory("search", query="deploy review", passages=2)
    assert page["hits"][0]["passages"] == [
        expected(GUIDE, 268, "Guide"),
        expected(GUIDE, 594, "Release"),
    ]
    one = storage.memory("search", query="deploy review", passages=1)
    assert passages(one) == [(594, "Release")]
    three = storage.memory("search", query="deploy review", passages=3)
    assert passages(three) == [(268, "Guide"), (594, "Release"), (925, "Release")]
    assert three["hits"][0]["passages"][2]["text"] == GUIDE[925:]
    ranked = storage.memory(
        "search", query="deploy review", passages=1, order="relevance"
    )
    assert passages(ranked) == [(594, "Release")] and "score" in ranked["hits"][0]


def test_headings_skip_fences_frontmatter_and_leading_comments(
    storage: Storage,
) -> None:
    storage.memory("write", path="fenced", content=FENCED)
    page = storage.memory("search", query="needle", passages=3)
    assert page["hits"][0]["passages"] == [expected(FENCED, 345, "Real")]


def test_short_values_paths_and_unrequested_passages(storage: Storage) -> None:
    storage.memory("write", path="needle/short", content="a short needle")
    requested = storage.memory("search", query="needle", passages=3)
    assert requested["hits"][0]["passages"] == []
    bodies: list[dict[str, Any]] = [{}, {"passages": 0}, {"passages": None}]
    for body in bodies:
        hit = storage.memory("search", query="needle", **body)["hits"][0]
        assert "passages" not in hit


def test_metadata_passages_have_no_heading(storage: Storage) -> None:
    storage.require("portable")
    document = {
        "scope": storage.scope,
        "path": "notes/meta",
        "content": "short needle",
        "version": 1,
        "created_at": "2026-10-24T10:00:00Z",
        "updated_at": "2026-10-24T10:00:00Z",
        "actor": "import:fixture",
        "redacted": False,
        "extra": {"notes": NOTES},
    }
    version = {
        k: document[k]
        for k in ("path", "content", "version", "created_at", "actor", "redacted")
    } | {"action": "created"}
    storage.server.post(
        "store/restore_scope",
        scope=storage.scope,
        documents=[document],
        versions=[version],
        redactions=[],
    )
    page = storage.memory(
        "search",
        query="needle",
        fields=["content", "metadata"],
        metadata_keys=["notes"],
        passages=3,
    )
    assert page["hits"][0]["passages"] == [
        {
            "field": "metadata",
            "metadata_key": "notes",
            "offset": 260,
            "text": NOTES[260:],
            "heading": None,
        }
    ]
    storage.memory("redact", path="notes/meta")
    assert storage.memory("search", query="needle", passages=3)["hits"] == []


